describe("LibWowRocks", function()
	local helper = require("tests.helper")

	it("returns a table from require when LibStub is absent", function()
		helper.clear_loaded()
		_G.LibStub = nil
		local WowRocks = require("LibWowRocks")
		assert.is_table(WowRocks)
		assert.equals("WowRocks-1.0", WowRocks.MAJOR)
		assert.equals(2, WowRocks.MINOR)
		assert.is_function(WowRocks.require)
		assert.is_table(WowRocks.package)
		assert.is_table(WowRocks.os)
		assert.is_table(WowRocks.io)
		assert.is_function(WowRocks.load)
	end)

	it("registers with LibStub and exposes the LibStdShim fields", function()
		local WowRocks, stub = helper.fresh()
		local Std = stub("LibStdShim-1.0")
		assert.equals(stub("WowRocks-1.0"), WowRocks)
		assert.equals("WowRocks-1.0", WowRocks.MAJOR)
		assert.equals(2, WowRocks.MINOR)
		assert.equals(Std.os, WowRocks.os)
		assert.equals(Std.io, WowRocks.io)
		assert.equals(Std.debug, WowRocks.debug)
		assert.equals(Std.bit32, WowRocks.bit32)
		assert.equals(Std.load, WowRocks.load)
		assert.equals(Std.loadfile, WowRocks.loadfile)
		assert.equals(Std.dofile, WowRocks.dofile)
		assert.equals(Std.bit32, WowRocks.require("bit32"))
	end)

	it("keeps the existing library when the minor is not newer", function()
		local WowRocks, stub = helper.fresh()
		local again, old = stub:NewLibrary("WowRocks-1.0", 2)
		assert.is_nil(again)
		assert.equals(WowRocks, stub("WowRocks-1.0"))
		package.loaded.LibWowRocks = nil
		assert.equals(true, require("LibWowRocks"))
		assert.equals(WowRocks, stub("WowRocks-1.0"))
	end)

	it("loads a preload and returns the cached module", function()
		local WowRocks = helper.fresh()
		local calls = 0
		WowRocks.package.preload.demo = function(name)
			calls = calls + 1
			return { name = name }
		end
		local first = WowRocks.require("demo")
		local second = WowRocks.require("demo")
		assert.equals(1, calls)
		assert.equals(first, second)
		assert.equals("demo", first.name)
	end)

	it("stores true when a preload returns nil", function()
		local WowRocks = helper.fresh()
		WowRocks.package.preload.empty = function() end
		assert.equals(true, WowRocks.require("empty"))
	end)

	it("errors when the module is missing or the name is not a string", function()
		local WowRocks = helper.fresh()
		local ok, err = pcall(WowRocks.require, "missing")
		assert.is_false(ok)
		assert.is_truthy(tostring(err):find("module 'missing' not found", 1, true))
		ok, err = pcall(WowRocks.require, 1)
		assert.is_false(ok)
		assert.is_truthy(tostring(err):find("string expected", 1, true))
	end)

	it("reports a loop while a module is still loading", function()
		local WowRocks = helper.fresh()
		WowRocks._begin("looping")
		local ok, err = pcall(WowRocks.require, "looping")
		assert.is_false(ok)
		assert.is_truthy(tostring(err):find("loop or previous error", 1, true))
	end)

	it("finishes a module with an explicit value or true", function()
		local WowRocks = helper.fresh()
		WowRocks._begin("sample")
		WowRocks._finish("sample", { ok = true }, true)
		assert.is_true(WowRocks.require("sample").ok)

		WowRocks._begin("blank")
		WowRocks._finish("blank", nil, true)
		assert.equals(true, WowRocks.require("blank"))

		WowRocks._begin("implicit")
		WowRocks._finish("implicit")
		assert.equals(true, WowRocks.package.loaded.implicit)
	end)

	it("accepts a module only when the version is newer", function()
		local WowRocks = helper.fresh()
		assert.is_true(WowRocks._accept("mod", "1.0-1"))
		assert.is_false(WowRocks._accept("mod", "1.0-1"))
		assert.is_true(WowRocks._accept("mod", "1.0-2"))
		assert.is_false(WowRocks._accept("mod", "0.9-1"))
		assert.is_true(WowRocks._accept("mod", "1.10-1"))
		assert.is_false(WowRocks._accept("mod", "1.2-1"))
	end)

	it("module fills _NAME, _M, and _PACKAGE", function()
		local WowRocks = helper.fresh()
		local function define()
			local M = WowRocks.module("pkg.mod")
			return M, _NAME, _M, _PACKAGE
		end
		local returned, name, env, pkg = define()
		assert.equals(returned, env)
		assert.equals("pkg.mod", name)
		assert.equals("pkg.", pkg)
		assert.equals(returned, WowRocks.package.loaded["pkg.mod"])
	end)

	it("package.loadlib errors and package.seeall indexes _G", function()
		local WowRocks = helper.fresh()
		local ok, err = pcall(WowRocks.package.loadlib)
		assert.is_false(ok)
		assert.is_truthy(tostring(err):find("package.loadlib is not available", 1, true))
		local env = {}
		WowRocks.package.seeall(env)
		assert.equals(print, env.print)
	end)
end)
